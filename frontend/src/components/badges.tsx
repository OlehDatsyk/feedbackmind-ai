import { Bot, FlaskConical, Hand, Ruler, Sparkles } from "lucide-react";
import { METHOD_LABELS, SENTIMENT_TONES, titleCase } from "@/lib/labels";
import type { Method, SentimentLabel } from "@/lib/types";
import { Badge, type Tone } from "./ui";

export function SentimentBadge({ label }: { label: SentimentLabel | string | null }) {
  if (!label) return <Badge tone="slate">Unclassified</Badge>;
  return <Badge tone={SENTIMENT_TONES[label] ?? "slate"}>{titleCase(label)}</Badge>;
}

export function MethodBadge({ method }: { method: Method | string | null }) {
  if (!method) return null;
  const icon = method === "ai" ? <Bot className="h-3 w-3" /> : method === "manual" ? <Hand className="h-3 w-3" /> : <Ruler className="h-3 w-3" />;
  const tone: Tone = method === "ai" ? "violet" : method === "manual" ? "blue" : "slate";
  return (
    <Badge tone={tone} title={METHOD_LABELS[method] ?? method}>
      {icon}
      {METHOD_LABELS[method] ?? method}
    </Badge>
  );
}

export function DemoBadge() {
  return (
    <Badge tone="amber" title="Synthetic demo data - not real customer feedback">
      <FlaskConical className="h-3 w-3" /> Demo
    </Badge>
  );
}

export function AIGeneratedBadge({ model }: { model?: string | null }) {
  return (
    <Badge tone="violet" title={model ? `Generated by ${model}` : "AI-generated"}>
      <Sparkles className="h-3 w-3" /> AI-generated
    </Badge>
  );
}

export function ImportanceBadge({ importance }: { importance: string }) {
  const tone: Tone = importance === "high" ? "red" : importance === "medium" ? "amber" : "slate";
  return <Badge tone={tone}>{titleCase(importance)} importance</Badge>;
}

export function StrengthBadge({ strength, n }: { strength: string; n?: number }) {
  const tone: Tone = strength === "strong" ? "green" : strength === "moderate" ? "blue" : "amber";
  return (
    <Badge tone={tone} title="Based on the number of supporting records: strong ≥ 30, moderate ≥ 10, limited < 10">
      {titleCase(strength)} evidence{n !== undefined ? ` · ${n} records` : ""}
    </Badge>
  );
}

export function LowSampleBadge() {
  return (
    <Badge tone="amber" title="Fewer records than the minimum sample size - treat as anecdotal">
      Small sample
    </Badge>
  );
}
